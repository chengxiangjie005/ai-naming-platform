-- AI 起名平台建表 SQL（在 Supabase → SQL Editor 中执行）
-- 表名：name_history

create table if not exists name_history (
  id bigint generated by default as identity primary key,
  user_requirement text not null,
  name_result text not null,
  model_name text not null,
  created_at timestamp with time zone default now()
);

-- 常用索引：按时间倒序查询历史记录
create index if not exists idx_name_history_created_at
  on name_history (created_at desc);

-- 调试期可临时关闭 RLS（正式上线必须按下面的方案收紧权限）
alter table name_history disable row level security;

